"""Real subprocess acceptance for durable workspace CLI operations.

Each command runs the currently tested interpreter with the inherited PATH.
The tiny video is generated by real FFmpeg; workspaces stay in pytest temp dirs.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import shutil
import sqlite3
import subprocess
import sys

import pytest


REPOSITORY = Path(__file__).resolve().parents[1]


@pytest.fixture(scope="module")
def cli_video(tmp_path_factory):
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg or not shutil.which("ffprobe"):
        pytest.skip("Real CLI admission requires FFmpeg and ffprobe")
    output = tmp_path_factory.mktemp("cli-media") / "实际 测试.mp4"
    subprocess.run([ffmpeg, "-v", "error", "-nostdin", "-y", "-f", "lavfi",
                    "-i", "testsrc2=duration=1:size=96x64:rate=10", "-pix_fmt", "yuv420p",
                    str(output)], check=True, capture_output=True, timeout=30)
    return output


@pytest.fixture()
def cli(tmp_path):
    log = tmp_path / "cli-evidence.jsonl"
    environment = os.environ.copy()
    environment["PYTHONIOENCODING"] = "utf-8"
    environment["PYTHONDONTWRITEBYTECODE"] = "1"

    def invoke(*arguments):
        command = [sys.executable, "-m", "trace_annotate.cli", "workspace", *map(str, arguments)]
        result = subprocess.run(command, cwd=REPOSITORY, env=environment, capture_output=True,
                                text=True, encoding="utf-8", timeout=90)
        with log.open("a", encoding="utf-8") as stream:
            stream.write(json.dumps({"argv": command, "cwd": str(REPOSITORY),
                                     "returncode": result.returncode, "stdout": result.stdout,
                                     "stderr": result.stderr}, ensure_ascii=False) + "\n")
        assert "Traceback (most recent call last)" not in result.stderr, result.stderr
        return result

    return invoke


def payload(result, expected=0):
    assert result.returncode == expected, (result.stdout, result.stderr)
    assert not result.stderr, result.stderr
    return json.loads(result.stdout)


def typed_error(result, expected_code):
    assert result.returncode == 1, (result.stdout, result.stderr)
    assert not result.stdout, result.stdout
    error = json.loads(result.stderr)["error"]
    assert error["code"] == expected_code
    assert error["request_id"] and isinstance(error["retryable"], bool)
    return error


@pytest.fixture()
def cli_project(cli, cli_video, tmp_path):
    project = tmp_path / "项目 space"
    payload(cli("init", "--project", project))
    admitted = payload(cli("import", "--project", project, cli_video))
    assert len(admitted["imported"]) == 1 and not admitted["failed"]
    return project, admitted["imported"][0]["task_id"]


def create_batch(cli, project, task_id, command_id="batch-command"):
    return payload(cli("batch", "create", "--project", project,
                       "--task-id", task_id, "--command-id", command_id))


def test_cli_mixed_import_partial_exit_and_persistent_failed_intakes(cli, cli_video, tmp_path):
    project = tmp_path / "mixed-workspace"
    missing = tmp_path / "missing.mp4"
    corrupt = tmp_path / "corrupt.mp4"
    corrupt.write_bytes(b"Not a valid media file.\x00\x01")
    source_hash = hashlib.sha256(cli_video.read_bytes()).hexdigest()
    payload(cli("init", "--project", project))

    result = payload(cli("import", "--project", project, missing, corrupt, cli_video), expected=1)
    assert len(result["imported"]) == 1
    assert [failure["display_name"] for failure in result["failed"]] == [missing.name, corrupt.name]
    assert result["failed"][0]["error_code"] == "SOURCE_MISSING"
    assert result["failed"][1]["error_code"] == "UNSUPPORTED_MEDIA"
    assert hashlib.sha256(cli_video.read_bytes()).hexdigest() == source_hash
    assert not missing.exists() and corrupt.read_bytes() == b"Not a valid media file.\x00\x01"

    # A new CLI process reopens the DB; failed records must not disappear.
    records = payload(cli("intakes", "--project", project))["intakes"]
    assert len(records) == 3
    assert [record["state"] for record in records] == ["failed", "failed", "succeeded"]
    assert [record["display_name"] for record in records] == [missing.name, corrupt.name, cli_video.name]
    assert records[0]["source_sha256"] is None and records[0]["source_size"] is None
    assert records[1]["source_sha256"] == hashlib.sha256(corrupt.read_bytes()).hexdigest()
    assert records[0]["task_id"] is None and records[1]["task_id"] is None
    assert records[2]["task_id"] == result["imported"][0]["task_id"]
    task = payload(cli("task", "--project", project, records[2]["task_id"]))
    assert task["revision"] == 0 and task["annotations"] == []


def test_cli_real_verify_batch_commits_one_candidate_without_labeling(cli, cli_project):
    project, task_id = cli_project
    batch = create_batch(cli, project, task_id)
    assert batch["jobs"][0]["state"] == "queued"
    assert batch["jobs"][0]["operation"] == "verify-media"
    result = payload(cli("batch", "run", "--project", project, "--batch-id", batch["id"]))
    assert len(result["executed"]) == 1
    job = result["executed"][0]
    assert job["state"] == "succeeded", job
    commit = job["commit"]
    assert commit["disposition"] == "candidate" and commit["input_still_current"] is True
    artifact = project / commit["artifact"]["relative_path"]
    data = artifact.read_bytes()
    assert hashlib.sha256(data).hexdigest() == commit["artifact"]["sha256"]
    verification = json.loads(data)
    assert verification["kind"] == "traceannotate.media-integrity"
    assert verification["frame_count"] == "10"
    assert verification["semantic_annotation"] == "not_performed"
    assert "exact frame-map arithmetic" in verification["scope"]

    repeated = payload(cli("batch", "run", "--project", project, "--batch-id", batch["id"]))
    assert repeated["executed"] == []
    latest = payload(cli("batch", "show", "--project", project, "--batch-id", batch["id"]))
    assert latest["jobs"][0]["commit"] == commit
    assert latest["jobs"][0]["attempt"] == 1
    task = payload(cli("task", "--project", project, task_id))
    assert task["revision"] == 0 and task["annotations"] == []
    with sqlite3.connect(project / "workspace.sqlite3") as database:
        assert database.execute("SELECT COUNT(*) FROM job_commits").fetchone()[0] == 1
        assert database.execute("SELECT COUNT(*) FROM durable_commits").fetchone()[0] == 1


def test_cli_pause_run_nonzero_resume_success_and_create_replay(cli, cli_project):
    project, task_id = cli_project
    batch = create_batch(cli, project, task_id)
    payload(cli("batch", "control", "--project", project, "--batch-id", batch["id"],
                "--action", "pause_dispatch", "--command-id", "pause-command"))
    paused = payload(cli("batch", "show", "--project", project, "--batch-id", batch["id"]))
    assert paused["dispatch_paused"] is True
    attempt = payload(cli("batch", "run", "--project", project, "--batch-id", batch["id"]), expected=1)
    assert attempt["executed"] == []
    assert attempt["batches"][0]["jobs"][0]["state"] == "queued"
    # Same command returns the original creation receipt, not a fresh batch.
    assert create_batch(cli, project, task_id) == batch
    payload(cli("batch", "control", "--project", project, "--batch-id", batch["id"],
                "--action", "resume_dispatch", "--command-id", "resume-command"))
    completed = payload(cli("batch", "run", "--project", project, "--batch-id", batch["id"]))
    assert len(completed["executed"]) == 1 and completed["executed"][0]["state"] == "succeeded"


def test_cli_export_is_new_snapshot_and_never_overwrites(cli, cli_project):
    project, task_id = cli_project
    first = payload(cli("export", "--project", project, "--name", "review-snapshot"))
    output = Path(first["exported"])
    assert output == project / "exports" / "review-snapshot.json"
    data = output.read_bytes()
    exported = json.loads(data)
    assert exported["tasks"][0]["id"] == task_id
    assert exported["kind"] == "traceannotate-workspace"
    typed_error(cli("export", "--project", project, "--name", "review-snapshot"), "EXPORT_EXISTS")
    assert output.read_bytes() == data
    second = payload(cli("export", "--project", project))
    third = payload(cli("export", "--project", project))
    assert second["exported"] != third["exported"]
    assert Path(second["exported"]).is_file() and Path(third["exported"]).is_file()
    typed_error(cli("export", "--project", project, "--name", "../escape"), "INVALID_ID")
    assert not (project / "escape.json").exists()


def test_cli_user_errors_are_typed_without_traceback(cli, cli_project, tmp_path):
    project, _ = cli_project
    typed_error(cli("task", "--project", project, "missing-task"), "TASK_NOT_FOUND")
    typed_error(cli("batch", "show", "--project", project, "--batch-id", "missing-batch"), "BATCH_NOT_FOUND")
    typed_error(cli("batch", "run", "--project", project, "--batch-id", "missing-batch"), "BATCH_NOT_FOUND")
    typed_error(cli("intakes", "--project", tmp_path / "missing-workspace"), "PROJECT_NOT_FOUND")
    typed_error(cli("init", "--project", project), "PROJECT_EXISTS")
    # A failed command must release the process lock so the next one can open.
    assert len(payload(cli("intakes", "--project", project))["intakes"]) == 1
